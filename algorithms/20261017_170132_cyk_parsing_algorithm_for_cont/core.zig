const std = @import("std");

pub const ProductionBinary = struct {
    left: u32,
    right1: u32,
    right2: u32,
};

pub const ProductionTerminal = struct {
    left: u32,
    terminal: u8,
};

pub const Grammar = struct {
    allocator: *std.mem.Allocator,
    nontermCount: u32,
    binaryProds: std.ArrayList(ProductionBinary),
    terminalProds: std.ArrayList(ProductionTerminal),

    pub fn init(allocator: *std.mem.Allocator, nontermCount: u32) Grammar {
        return Grammar{
            .allocator = allocator,
            .nontermCount = nontermCount,
            .binaryProds = std.ArrayList(ProductionBinary).init(allocator.*),
            .terminalProds = std.ArrayList(ProductionTerminal).init(allocator.*),
        };
    }

    pub fn deinit(self: *Grammar) void {
        self.binaryProds.deinit();
        self.terminalProds.deinit();
    }

    pub fn addBinary(self: *Grammar, left: u32, right1: u32, right2: u32) !void {
        try self.binaryProds.append(ProductionBinary{
            .left = left,
            .right1 = right1,
            .right2 = right2,
        });
    }

    pub fn addTerminal(self: *Grammar, left: u32, terminal: u8) !void {
        try self.terminalProds.append(ProductionTerminal{
            .left = left,
            .terminal = terminal,
        });
    }

    // CYK algorithm: returns true if input is generated by the grammar.
    // Assumes start symbol has id 0.
    pub fn cyk(self: *const Grammar, input: []const u8) bool {
        const n = input.len;
        if (n == 0) return false; // No epsilon handling for simplicity.

        const BitSet = std.bit_set.DynamicBitSet;
        const allocator = self.allocator.*;

        // Allocate a flat array of BitSets: table[start][len-1] => index = start * n + (len-1)
        var table = try allocator.alloc(BitSet, n * n);
        defer allocator.free(table);

        // Initialize each BitSet with capacity = nontermCount
        var i: usize = 0;
        while (i < table.len) : (i += 1) {
            table[i] = BitSet.init(allocator, self.nontermCount);
        }
        defer {
            // Deinit all BitSets
            var j: usize = 0;
            while (j < table.len) : (j += 1) {
                table[j].deinit();
            }
        }

        // Helper to get reference to BitSet at (start, len)
        fn cell(start: usize, len: usize) *BitSet {
            return &table[start * n + (len - 1)];
        }

        // Fill length-1 cells using terminal productions
        for (input) |ch, idx| {
            const bs = cell(idx, 1);
            for (self.terminalProds.items) |prod| {
                if (prod.terminal == ch) {
                    bs.set(prod.left);
                }
            }
        }

        // Main CYK loops
        var l: usize = 2;
        while (l <= n) : (l += 1) {
            var s: usize = 0;
            while (s <= n - l) : (s += 1) {
                const cur = cell(s, l);
                var p: usize = 1;
                while (p < l) : (p += 1) {
                    const leftSet = cell(s, p);
                    const rightSet = cell(s + p, l - p);
                    // For each binary production, check membership
                    for (self.binaryProds.items) |prod| {
                        if (leftSet.isSet(prod.right1) and rightSet.isSet(prod.right2)) {
                            cur.set(prod.left);
                        }
                    }
                }
            }
        }

        // Accept if start symbol (0) is in cell(0, n)
        return cell(0, n).isSet(0);
    }
};
