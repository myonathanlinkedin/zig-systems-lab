const std = @import("std");

pub const BinaryProd = struct {
    left: usize,
    right1: usize,
    right2: usize,
};

pub const Grammar = struct {
    /// Index of the start non‑terminal (usually 0)
    start: usize,
    /// For each possible terminal byte, a bitmask of non‑terminals that produce it
    terminal_masks: [256]u64,
    /// List of binary productions A → B C
    binary_productions: []const BinaryProd,
};

/// Build a bitmask with a single bit set at `idx`.  `idx` must be < 64.
inline fn bit(idx: usize) u64 {
    return @as(u64, 1) << @intCast(u6, idx);
}

/// CYK recognizer. Returns `true` iff `input` belongs to the language generated by `g`.
pub fn parse(g: Grammar, input: []const u8) bool {
    const n = input.len;
    if (n == 0) return false; // empty string not accepted in this implementation

    // Allocate a flat n×n table of u64 masks.
    const allocator = std.heap.page_allocator;
    var table = allocator.alloc(u64, n * n) catch return false;
    defer allocator.free(table);
    // Initialise to zero.
    for (table) |*cell| cell.* = 0;

    // Fill the diagonal with terminal productions.
    for (input) |ch, i| {
        const mask = g.terminal_masks[ch];
        table[i * n + i] = mask;
    }

    // Length of the span (2 .. n)
    var span: usize = 2;
    while (span <= n) : (span += 1) {
        var i: usize = 0;
        while (i + span <= n) : (i += 1) {
            const j = i + span - 1;
            var cell_mask: u64 = 0;

            // Try every possible split point.
            var k: usize = i;
            while (k < j) : (k += 1) {
                const left_mask = table[i * n + k];
                const right_mask = table[(k + 1) * n + j];
                if (left_mask == 0 or right_mask == 0) continue;

                // Test each binary production.
                for (g.binary_productions) |prod| {
                    const left_has = (left_mask & bit(prod.right1)) != 0;
                    const right_has = (right_mask & bit(prod.right2)) != 0;
                    if (left_has and right_has) {
                        cell_mask |= bit(prod.left);
                    }
                }
            }
            table[i * n + j] = cell_mask;
        }
    }

    // Accept if the start symbol appears in the top‑right cell.
    const final_mask = table[0 * n + (n - 1)];
    return (final_mask & bit(g.start)) != 0;
}
